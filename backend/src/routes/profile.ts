import { Hono } from 'hono';
import { supabase } from '../db/supabase';
import { authMiddleware, AuthVariables } from '../middleware/auth';

export const profileRouter = new Hono<{ Variables: AuthVariables }>();

// Apply auth middleware to all profile routes
profileRouter.use('*', authMiddleware);

// GET /api/profile/me - Get current user's profile and karma status (FR-01, FR-02)
profileRouter.get('/me', async (c) => {
  const user = c.get('user');

  try {
    const { data: profile, error } = await supabase
      .from('profiles')
      .select('*')
      .eq('id', user.id)
      .maybeSingle();

    if (error) {
      throw error;
    }

    if (!profile) {
      // Auto-fallback: If profile record hasn't been generated by DB trigger yet, create one
      const fallbackName =
        user.user_metadata?.full_name ||
        user.user_metadata?.name ||
        user.email?.split('@')[0] ||
        'Pengguna Mabar';

      const newProfile = {
        id: user.id,
        email: user.email || '',
        full_name: fallbackName,
        avatar_url: user.user_metadata?.avatar_url || null,
        credit_score: 100,
        total_sessions_completed: 0,
        show_up_rate: 100.0,
        is_suspended: false
      };

      const { data: inserted, error: insertErr } = await supabase
        .from('profiles')
        .insert(newProfile)
        .select()
        .single();

      if (insertErr) {
        // Return constructed fallback if DB insert fails
        return c.json({ success: true, profile: newProfile });
      }

      return c.json({ success: true, profile: inserted });
    }

    return c.json({ success: true, profile });
  } catch (err: any) {
    return c.json(
      {
        success: false,
        message: 'Gagal mengambil data profil pengguna',
        error: err.message
      },
      500
    );
  }
});

// PUT /api/profile/me - Update user profile details (FR-02)
profileRouter.put('/me', async (c) => {
  const user = c.get('user');

  try {
    const body = await c.req.json();
    const { full_name, phone_number, avatar_url } = body;

    const updates: Record<string, any> = {
      updated_at: new Date().toISOString()
    };

    if (typeof full_name === 'string' && full_name.trim().length > 0) {
      updates.full_name = full_name.trim();
    }
    if (typeof phone_number === 'string') {
      updates.phone_number = phone_number.trim();
    }
    if (typeof avatar_url === 'string') {
      updates.avatar_url = avatar_url.trim();
    }

    const { data, error } = await supabase
      .from('profiles')
      .update(updates)
      .eq('id', user.id)
      .select()
      .single();

    if (error) throw error;

    return c.json({ success: true, profile: data });
  } catch (err: any) {
    return c.json(
      {
        success: false,
        message: 'Gagal memperbarui profil pengguna',
        error: err.message
      },
      500
    );
  }
});

// GET /api/profile/activities - Get user's sport/esport identities & skill ratings (FR-02, FR-11)
profileRouter.get('/activities', async (c) => {
  const user = c.get('user');

  try {
    const { data, error } = await supabase
      .from('user_activity_profiles')
      .select('*')
      .eq('user_id', user.id)
      .order('activity_type', { ascending: true });

    if (error) throw error;

    return c.json({ success: true, activities: data || [] });
  } catch (err: any) {
    return c.json(
      {
        success: false,
        message: 'Gagal mengambil sub-profil aktivitas',
        error: err.message
      },
      500
    );
  }
});

// POST /api/profile/activities - Upsert sport/esport activity profile (FR-02, FR-11)
profileRouter.post('/activities', async (c) => {
  const user = c.get('user');

  try {
    const body = await c.req.json();
    const {
      activity_type,
      in_game_name,
      game_id_tag,
      preferred_role,
      skill_rating_level,
      skill_rating_points
    } = body;

    if (!activity_type) {
      return c.json(
        {
          success: false,
          message: 'Parameter activity_type wajib diisi.'
        },
        400
      );
    }

    const normalizedActivity = activity_type.toLowerCase().trim();
    const validLevels = ['Beginner', 'Intermediate', 'Advanced'];
    const resolvedLevel = validLevels.includes(skill_rating_level)
      ? skill_rating_level
      : 'Beginner';

    const payload = {
      user_id: user.id,
      activity_type: normalizedActivity,
      in_game_name: in_game_name?.trim() || null,
      game_id_tag: game_id_tag?.trim() || null,
      preferred_role: preferred_role?.trim() || null,
      skill_rating_level: resolvedLevel,
      skill_rating_points: typeof skill_rating_points === 'number' ? skill_rating_points : 1200,
      updated_at: new Date().toISOString()
    };

    const { data, error } = await supabase
      .from('user_activity_profiles')
      .upsert(payload, { onConflict: 'user_id,activity_type' })
      .select()
      .single();

    if (error) throw error;

    return c.json({ success: true, activity: data });
  } catch (err: any) {
    return c.json(
      {
        success: false,
        message: 'Gagal menyimpan sub-profil aktivitas',
        error: err.message
      },
      500
    );
  }
});

// GET /api/profile/me/credit-history - Get current user's Credit Score transactions (FR-10)
profileRouter.get('/me/credit-history', async (c) => {
  const user = c.get('user');

  try {
    const { data, error } = await supabase
      .from('credit_transactions')
      .select('id, user_id, session_id, delta, reason, balance_after, created_at')
      .eq('user_id', user.id)
      .order('created_at', { ascending: false });

    if (error) throw error;

    return c.json({ success: true, transactions: data || [] });
  } catch (err: any) {
    return c.json(
      {
        success: false,
        message: 'Gagal mengambil riwayat Credit Score',
        error: err.message
      },
      500
    );
  }
});
